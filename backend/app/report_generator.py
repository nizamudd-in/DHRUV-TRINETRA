"""
Server-side report generation for POLAR-TWIN.

Builds real, current-data reports from live simulator state:
- build_report_pdf_bytes(): a genuine PDF (via PyMuPDF's Story/DocumentWriter,
  rendering an HTML document server-side — no placeholder PDF library needed).
- build_telemetry_csv(): a genuine CSV of current + historical asset/station
  telemetry.

Everything produced here is explicitly labeled prototype/demonstration output —
see PROTOTYPE_DISCLAIMER. Nothing here claims to be an official NCPOR report,
a certified instrument reading, or a trained ML output.
"""
import csv
import io
import random
from datetime import datetime, timedelta, timezone
from typing import Any

import pymupdf as fitz  # PyMuPDF; `fitz` is the deprecated alias for the same package

from .simulator import simulator
from .ai_engine import ai_engine
from .health_model import calculate_asset_health

PROTOTYPE_DISCLAIMER = (
    "Prototype / Demonstration Output — Not an official NCPOR report. "
    "All equipment telemetry is generated by the POLAR-TWIN prototype simulator. "
    "Health, risk and AI recommendation figures are produced by deterministic prototype "
    "models, not certified instrumentation or a trained ML system."
)


def _esc(value: Any) -> str:
    return str(value).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _severity_color(level: str) -> str:
    level = (level or "").upper()
    if level in ("CRITICAL", "HIGH", "EMERGENCY"):
        return "#ef4444"
    if level in ("MEDIUM", "WARNING", "ADVISORY"):
        return "#f59e0b"
    return "#10b981"


def report_filename(station_id: str, ext: str) -> str:
    sid = station_id.upper()
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d_%H-%M")
    label = "Report" if ext == "pdf" else "Telemetry"
    return f"POLAR-TWIN_{sid}_{label}_{ts}.{ext}"


def build_report_html(station_id: str) -> str:
    sid = station_id.upper()
    station = simulator.stations.get(sid)
    if not station:
        raise ValueError(f"Station '{station_id}' not found")

    assets = simulator.assets.get(sid, [])
    alerts = [a for a in simulator.alerts if a.stationId == sid]
    inventory = [i for i in simulator.inventory if i.stationId == sid]
    critical_inventory = [i for i in inventory if i.status in ("stockout_risk", "reorder_required")]
    work_orders = [w for w in simulator.work_orders if w.stationId == sid]
    decisions = [d for d in simulator.decisions.values() if d.stationId == sid]
    audit = [e for e in simulator.audit_log if e.get("stationId") == sid][:10]
    risk = ai_engine.calculate_cross_domain_risk(sid)

    now = datetime.now(timezone.utc)
    timestamp_str = now.strftime("%d-%b-%Y %H:%M UTC")

    equipment_rows = "".join(f"""
        <tr>
          <td>{_esc(a.assetId)}<br/><span class="muted">{_esc(a.name)}</span></td>
          <td>{_esc(a.type)}</td>
          <td style="color:{_severity_color(a.status)};font-weight:bold;">{_esc(a.status.upper())}</td>
          <td>{a.healthScore:.1f}% ({_esc(calculate_asset_health(a)['status'])})</td>
          <td>{a.vibration:.2f} mm/s</td>
          <td>{a.temperature:.1f}°C</td>
          <td>{_esc(a.failureRisk)}</td>
          <td>{a.predictedFailureDays if a.predictedFailureDays is not None else '&mdash;'}</td>
        </tr>""" for a in sorted(assets, key=lambda x: x.healthScore))

    alert_rows = "".join(f"""
        <tr>
          <td style="color:{_severity_color(al.level)};font-weight:bold;">{_esc(al.level.upper())}</td>
          <td>{_esc(al.title)}</td>
          <td>{_esc(al.assetId or '&mdash;')}</td>
          <td>{'Acknowledged' if al.acknowledged else 'ACTIVE'}</td>
          <td>{al.riskScore:.0f}</td>
        </tr>""" for al in alerts) or '<tr><td colspan="5" class="muted">No alerts recorded.</td></tr>'

    inventory_rows = "".join(f"""
        <tr>
          <td>{_esc(i.name)}</td>
          <td>{i.quantity} {_esc(i.unit)}</td>
          <td>{i.daysRemaining}d</td>
          <td>{_esc(i.status.replace('_', ' '))}</td>
        </tr>""" for i in critical_inventory) or '<tr><td colspan="4" class="muted">No critical stockout/reorder items.</td></tr>'

    wo_rows = "".join(f"""
        <tr>
          <td>{_esc(w.orderId)}</td>
          <td>{_esc(w.assetId)}</td>
          <td>{_esc(w.priority)}</td>
          <td>{_esc(w.status.replace('_', ' '))}</td>
          <td>{_esc(w.assignedTechnician)}</td>
        </tr>""" for w in work_orders) or '<tr><td colspan="5" class="muted">No work orders recorded.</td></tr>'

    decision_rows = "".join(f"""
        <tr>
          <td>{_esc(d.id)}</td>
          <td>{_esc(d.assetId or 'Station-level')}</td>
          <td>{_esc(d.proposedAction)}</td>
          <td>{_esc(d.approvalStatus)}</td>
          <td>{_esc(d.approvedBy or '&mdash;')}</td>
        </tr>""" for d in decisions) or '<tr><td colspan="5" class="muted">No AI recommendations generated this session.</td></tr>'

    audit_rows = "".join(f"""
        <tr><td>{_esc(str(e.get('timestamp', ''))[:19].replace('T', ' '))}</td><td>{_esc(e.get('actor', ''))}</td><td>{_esc(e.get('action', ''))}</td></tr>
    """ for e in audit) or '<tr><td colspan="3" class="muted">No audit events recorded this session.</td></tr>'

    domain_rows = "".join(f"""
        <tr>
          <td>{_esc(d.domain.capitalize())}</td>
          <td style="color:{_severity_color(d.severity)};font-weight:bold;">{_esc(d.severity)}</td>
          <td>{d.score:.1f}</td>
          <td class="muted">{_esc(d.reason)}</td>
        </tr>""" for d in risk.domainRisks)

    return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"/>
<style>
  body {{ font-family: Helvetica, Arial, sans-serif; color: #111; font-size: 10.5px; line-height: 1.4; }}
  h1 {{ font-size: 19px; color: #0284c7; margin: 0 0 2px 0; }}
  h2 {{ font-size: 13px; color: #075985; margin: 14px 0 6px 0; border-bottom: 1px solid #cbd5e1; padding-bottom: 3px; }}
  .subtitle {{ font-size: 10px; color: #555; margin-bottom: 10px; }}
  .banner {{ background: #fff7ed; border: 1px solid #f59e0b; padding: 8px 10px; font-size: 9.5px; color: #7c2d12; margin-bottom: 10px; }}
  .muted {{ color: #666; font-size: 9px; }}
  table {{ width: 100%; border-collapse: collapse; margin-bottom: 4px; }}
  th {{ background: #0f172a; color: #fff; text-align: left; padding: 4px 6px; font-size: 9px; }}
  td {{ border-bottom: 1px solid #e2e8f0; padding: 4px 6px; font-size: 9px; vertical-align: top; }}
  .meta {{ background: #f1f5f9; padding: 8px 10px; margin-bottom: 10px; }}
  .meta span {{ display: inline-block; width: 24%; font-size: 9px; }}
  .footer {{ margin-top: 16px; padding-top: 8px; border-top: 1px solid #cbd5e1; font-size: 8.5px; color: #777; }}
</style></head>
<body>
  <h1>POLAR-TWIN &mdash; {_esc(station.name)} Report</h1>
  <div class="subtitle">Generated {timestamp_str} &bull; Prototype / Demonstration Output</div>
  <div class="banner"><b>{_esc(PROTOTYPE_DISCLAIMER)}</b></div>

  <div class="meta">
    <span><b>Station:</b> {_esc(station.name)} ({_esc(station.stationId)})</span>
    <span><b>Status:</b> {_esc(station.status.upper())}</span>
    <span><b>Health Index:</b> {station.healthScore:.1f}%</span>
    <span><b>Connectivity:</b> {_esc(station.connectivity)}</span><br/>
    <span><b>Coordinates:</b> {_esc(station.coordinates)}</span>
    <span><b>Personnel:</b> {station.personnelCount}</span>
    <span><b>Power Load:</b> {station.powerLoadKw:.0f} / {station.powerCapacityKw:.0f} kW</span>
    <span><b>BESS SOC:</b> {station.batterySoc:.0f}%</span>
  </div>

  <h2>Cross-Domain Risk Summary <span class="muted">(POLAR-TWIN prototype risk engine)</span></h2>
  <div class="muted" style="margin-bottom:6px;">Overall: <b style="color:{_severity_color(risk.overallRisk)}">{_esc(risk.overallRisk)}</b> ({risk.overallScore:.1f}/100) &mdash; Primary driver: {_esc(risk.primaryDriver)}</div>
  <table><tr><th>Domain</th><th>Severity</th><th>Score</th><th>Reason</th></tr>{domain_rows}</table>

  <h2>Equipment &amp; Calculated Health <span class="muted">(simulated telemetry; prototype health model)</span></h2>
  <table><tr><th>Asset</th><th>Type</th><th>Status</th><th>Health</th><th>Vibration</th><th>Temp</th><th>Failure Risk</th><th>Est. Days to Failure</th></tr>{equipment_rows}</table>

  <h2>Active &amp; Historical Alerts</h2>
  <table><tr><th>Level</th><th>Title</th><th>Asset</th><th>State</th><th>Risk Score</th></tr>{alert_rows}</table>

  <h2>Critical Inventory / Logistics</h2>
  <table><tr><th>Item</th><th>Quantity</th><th>Days Remaining</th><th>Status</th></tr>{inventory_rows}</table>

  <h2>Work Orders</h2>
  <table><tr><th>ID</th><th>Asset</th><th>Priority</th><th>Status</th><th>Technician</th></tr>{wo_rows}</table>

  <h2>AI Recommendation / Decision Summary <span class="muted">(prototype decision engine)</span></h2>
  <table><tr><th>Decision ID</th><th>Asset</th><th>Proposed Action</th><th>Status</th><th>Approved By</th></tr>{decision_rows}</table>

  <h2>Recent Audit Trail</h2>
  <table><tr><th>Timestamp (UTC)</th><th>Actor</th><th>Action</th></tr>{audit_rows}</table>

  <div class="footer">
    Generated by PolarTwin Prototype Engine &bull; {timestamp_str}<br/>
    Prototype / Demonstration &mdash; Not an official NCPOR system. No official signatures, certifications or approvals are implied.
  </div>
</body></html>"""


def build_report_pdf_bytes(station_id: str) -> bytes:
    html = build_report_html(station_id)
    mediabox = fitz.paper_rect("a4")
    where = mediabox + (28, 28, -28, -28)
    story = fitz.Story(html=html)
    buf = io.BytesIO()
    writer = fitz.DocumentWriter(buf, "")
    more = 1
    while more:
        dev = writer.begin_page(mediabox)
        more, _ = story.place(where)
        story.draw(dev)
        writer.end_page()
    writer.close()
    return buf.getvalue()


def build_telemetry_csv(station_id: str) -> str:
    sid = station_id.upper()
    station = simulator.stations.get(sid)
    if not station:
        raise ValueError(f"Station '{station_id}' not found")
    assets = simulator.assets.get(sid, [])

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "timestamp", "station", "asset_id", "asset_name", "asset_type",
        "metric", "value", "unit", "health_score", "status", "source_type"
    ])

    now = datetime.now(timezone.utc).replace(microsecond=0)

    for a in assets:
        # Current snapshot
        for metric, value, unit in [
            ("vibration", a.vibration, "mm/s"),
            ("temperature", a.temperature, "C"),
            ("power", a.powerKw, "kW"),
            ("runtime_hours", a.runtimeHours, "h"),
        ]:
            writer.writerow([now.isoformat(), sid, a.assetId, a.name, a.type,
                              metric, value, unit, a.healthScore, a.status, "SIMULATED"])

        # 24h historical trend (same generation approach as /api/assets/{id}/telemetry)
        for hours_ago in range(23, -1, -1):
            ts = now - timedelta(hours=hours_ago)
            jitter = hours_ago > 0
            vib = round(max(0.1, a.vibration + (random.uniform(-0.15, 0.15) if jitter else 0)), 2)
            temp = round(a.temperature + (random.uniform(-1.2, 1.2) if jitter else 0), 1)
            power = round(max(0.0, a.powerKw + (random.uniform(-5.0, 5.0) if jitter else 0)), 1)
            writer.writerow([ts.isoformat(), sid, a.assetId, a.name, a.type, "vibration", vib, "mm/s", "", "", "SIMULATED"])
            writer.writerow([ts.isoformat(), sid, a.assetId, a.name, a.type, "temperature", temp, "C", "", "", "SIMULATED"])
            writer.writerow([ts.isoformat(), sid, a.assetId, a.name, a.type, "power", power, "kW", "", "", "SIMULATED"])

    for metric, value, unit in [
        ("ambient_temperature", station.currentTemp, "C"),
        ("wind_speed", station.windSpeedKts, "kts"),
        ("power_load", station.powerLoadKw, "kW"),
        ("power_capacity", station.powerCapacityKw, "kW"),
        ("battery_soc", station.batterySoc, "%"),
        ("fuel_days_remaining", station.fuelDaysRemaining, "days"),
    ]:
        writer.writerow([now.isoformat(), sid, "", station.name, "station",
                          metric, value, unit, station.healthScore, station.status, "SIMULATED"])

    return output.getvalue()
